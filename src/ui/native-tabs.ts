/** A top-level native menu tab positioned relative to the 1440px reference window. */
export interface NativeTab {
  id: string;
  label: string;
  hasDropdown: boolean;
  x: number;
  width: number;
  icon?: string;
  disabled?: boolean;
  accessibleLabel?: string;
}

/** A native ribbon control whose coordinates are relative to the ribbon's top-left corner. */
export interface RibbonItem {
  id: string;
  label: string;
  action: string;
  icon: string;
  x: number;
  y: number;
  width: number;
  height: number;
  hasDropdown?: boolean;
  disabled?: boolean;
  selected?: boolean;
  size?: "large" | "compact" | "toggle" | "field" | "gallery" | "icon";
  value?: string;
  shortcut?: string;
  showLabel?: boolean;
  tooltip?: string;
  gallery?: "shapes" | "styles";
}

/** A contiguous group of native ribbon controls separated from adjacent groups. */
export interface RibbonGroup {
  id: string;
  x: number;
  width: number;
  label?: string;
  items: readonly RibbonItem[];
}
/** A measured ribbon gallery viewport containing its native tile grid and scroll controls. */
export interface NativeRibbonGallery {
  id: string;
  kind: "shapes" | "styles";
  x: number;
  y: number;
  width: number;
  height: number;
  columns: number;
  rows: number;
}

/** A native dropdown entry retaining its visible label and optional keyboard shortcut. */
export interface NativeMenuItem {
  id: string;
  label: string;
  action: string;
  shortcut?: string;
  icon?: string;
  disabled?: boolean;
  checked?: boolean;
  separatorBefore?: boolean;
  children?: readonly NativeMenuItem[];
  hasDropdown?: boolean;
  plainLabel?: string;
  mnemonic?: string;
  kind?: "command" | "recent-slot";
  recentIndex?: number;
  x?: number;
  y?: number;
  width?: number;
  height?: number;
}

