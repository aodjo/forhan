/**
 * Build a large native ribbon command from measured blank-window geometry.
 *
 * Keeps the common 6px top inset and 76px control height explicit so the
 * renderer can reproduce native spacing without inferring it from text width.
 *
 * @param {string} id - Stable control identifier used by renderer events.
 * @param {string} label - The visible native Korean command label.
 * @param {string} icon - The independent native-style icon name.
 * @param {string} action - Logical command dispatched by the renderer.
 * @param {number} x - Horizontal control origin relative to the native window.
 * @param {number} width - The native control width in CSS pixels at 96 DPI.
 * @param {boolean} hasDropdown - Whether the native command displays a dropdown arrow.
 * @param {string | undefined} shortcut - The native ribbon access-key text, when observed.
 * @returns {RibbonItem} A fully positioned native ribbon command.
 * @example
 * largeItem('cut', '오려 두기', 'cut', 'cut', 15, 38, false, 'ALT+T');
 */
function largeItem(
  id: string,
  label: string,
  icon: string,
  action: string,
  x: number,
  width: number,
  hasDropdown = false,
  shortcut?: string,
): RibbonItem {
  return {
    id,
    label,
    icon,
    action,
    x,
    y: 6,
    width,
    height: 76,
    hasDropdown,
    size: "large",
    ...(shortcut ? { shortcut } : {}),
  };
}

