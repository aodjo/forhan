/**
 * Resolve a native tab label or stable identifier to its ribbon command set.
 *
 * Returns an empty collection for unknown or contextual tabs so the renderer
 * never substitutes unrelated editing commands for an uncaptured native tab.
 *
 * @param {string} tab - A stable tab identifier or its visible Korean label.
 * @returns {readonly RibbonItem[]} The measured native controls for the requested tab.
 * @example
 * getRibbonItems('편집');
 */
export function getRibbonItems(tab: string): readonly RibbonItem[] {
  /** The caller's tab name normalized to the visible native label's spacing convention. */
  const normalized = tab.trim().replace(/\s+/g, "");
  for (/** The native top-level tab checked for a stable identifier or Korean label match. */ const candidate of nativeTabs) {
    if (
      candidate.id === normalized ||
      candidate.label.replace(/\s+/g, "") === normalized
    )
      return ribbonItems[candidate.id] || [];
  }
  return [];
}

/**
 * Group adjacent measured ribbon controls at native separator gaps.
 *
 * Native 13px gaps separate command clusters in the default ribbon. Controls
 * with smaller gaps remain together, retaining their original absolute origins.
 *
 * @param {string} tab - A stable tab identifier or its visible Korean label.
 * @returns {readonly RibbonGroup[]} Contiguous command clusters with native bounds.
 * @example
 * getRibbonGroups('edit');
 */
export function getRibbonGroups(tab: string): readonly RibbonGroup[] {
  /** The measured ribbon controls associated with the requested native tab. */
  const items = getRibbonItems(tab);
  /** Contiguous native command groups accumulated without changing control coordinates. */
  const groups: Array<{
    id: string;
    x: number;
    width: number;
    items: RibbonItem[];
  }> = [];
  for (/** The native control assigned to its contiguous ribbon cluster. */ const item of items) {
    /** The last accumulated group, if the current control can join it. */
    const previous = groups.at(-1);
    if (previous && item.x - (previous.x + previous.width) < 10) {
      previous.items.push(item);
      /** The rightmost native bound after controls from another ribbon row join this group. */
      const right = Math.max(previous.x + previous.width, item.x + item.width);
      previous.x = Math.min(previous.x, item.x);
      previous.width = right - previous.x;
    } else
      groups.push({
        id: `${tab}-group-${groups.length + 1}`,
        x: item.x,
        width: item.width,
        items: [item],
      });
  }
  return groups;
}
