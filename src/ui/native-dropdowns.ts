/**
 * Retrieve a measured native dropdown for one top-level menu tab.
 *
 * Visible Korean text, shortcuts, states and geometry remain separate from the
 * application's logical actions. Unknown tabs return no menu rather than
 * fabricating entries or exposing inherited object properties.
 *
 * @param {string} tabId Stable tab identifier used by the native ribbon renderer.
 * @returns {NativeDropdown | undefined} The observed dropdown or undefined for an uncaptured tab.
 * @example
 * getNativeDropdown("edit") // Observed Edit menu geometry and command entries.
 * getNativeDropdown("unknown") // undefined
 */
export function getNativeDropdown(tabId: string): NativeDropdown | undefined {
  return Object.prototype.hasOwnProperty.call(NATIVE_DROPDOWNS, tabId)
    ? NATIVE_DROPDOWNS[tabId]
    : undefined;
}
