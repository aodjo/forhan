/** Rectangle measured in CSS pixels relative to the owned native reference window. */
export interface NativeDropdownBounds {
  x: number;
  y: number;
  width: number;
  height: number;
}

/** An observed native command with its visible text and separate application action. */
export interface NativeDropdownItem {
  id: string;
  label: string;
  shortcut?: string;
  icon?: string;
  action: string;
  checked?: boolean;
  disabled?: boolean;
  separatorBefore?: boolean;
  hasDropdown?: boolean;
  children?: readonly NativeDropdownItem[];
  mnemonic?: string;
  plainLabel?: string;
  observedName?: string;
  observedControlType?: string;
  observedHelp?: string;
  observedAccessKey?: string;
  observedExpandState?: string;
  observedToggleState?: string;
  bounds?: NativeDropdownBounds;
}

/** A measured native top-tab dropdown containing only runtime-observed entries. */
export interface NativeDropdown extends NativeDropdownBounds {
  id: string;
  items: readonly NativeDropdownItem[];
  referenceWidth: number;
  referenceHeight: number;
  evidence: string;
  /** Original UIA window bounds, including the native three-pixel drop shadow. */
  observedBounds?: NativeDropdownBounds;
}

