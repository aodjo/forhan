import { test, expect, type Page } from "@playwright/test";
import { readFile } from "node:fs/promises";
import { readHwp } from "../src/formats/hwp.ts";
import { readHwpx } from "../src/formats/hwpx.ts";

/**
 * Load independent source shadow definitions through the ordinary document input.
 *
 * Mixed runs use different kinds, signed offsets, colors and font sizes so an
 * unrelated representative edit cannot silently flatten their source fields.
 * @async
 * @param {Page} page - Owned renderer page.
 * @param {boolean} [mixed=false] - Whether to append a differently styled source run.
 * @returns {Promise<void>} Resolves when the actual editable shadows render.
 * @example
 * await loadShadow(page,true); // DROP and CONTINUOUS remain independent.
 */
async function loadShadow(page: Page, mixed = false): Promise<void> {
  /** Authored source values are independent of the product's control implementation. */
  const content = [];
  for (let index = 0; index < (mixed ? 2 : 1); index++)
    content.push({
      type: "text",
      text: index ? " Second 한글" : "Shadow 한글",
      marks: [
        {
          type: "textStyle",
          attrs: {
            fontSize: index ? "20pt" : "16pt",
            color: "#112233",
            nativeShadowType: index ? "CONTINUOUS" : "DROP",
            nativeShadowOffsetX: index ? 10 : -20,
            nativeShadowOffsetY: index ? -10 : 30,
            nativeShadowColor: index ? "#654321" : "#123456",
          },
        },
        {
          type: "underline",
          attrs: {
            nativePosition: "TOP",
            nativePattern: 11,
            nativeColor: "#775533",
          },
        },
      ],
    });
  await page
    .locator("#file-input")
    .setInputFiles({
      name: "shadow.forhan",
      mimeType: "application/json",
      buffer: Buffer.from(
        JSON.stringify({
          application: "forhan",
          version: 1,
          title: "Native shadow",
          doc: { type: "doc", content: [{ type: "paragraph", content }] },
        }),
      ),
    });
  await expect(page.locator(".tiptap [data-forhan-shadow]")).toHaveCount(
    mixed ? 2 : 1,
  );
}

/**
 * Open the actual native shadow group while retaining the selected source runs.
 *
 * The whole selection remains active across ribbon and dialog focus changes.
 * @async
 * @param {Page} page - Owned renderer.
 * @returns {Promise<void>} Resolves with the real Expanded panel visible.
 * @example
 * await openShadow(page); // The document remains unchanged until Apply.
 */
async function openShadow(page: Page): Promise<void> {
  await page.locator(".tiptap").press("ControlOrMeta+a");
  await page.locator('button[data-native-tab="format"]').click();
  await page
    .locator('.native-ribbon [data-native-action="char-format"]')
    .click();
  await page.locator('[data-character-tab="expanded"]').click();
}

/**
 * Read actual native or HTML output from the production browser export command.
 *
 * Only the browser download is observed; writers supply all generated bytes.
 * @async
 * @param {Page} page - Owned renderer.
 * @param {'hwp'|'hwpx'|'html'} format - Actual selected output format.
 * @returns {Promise<Buffer>} Complete unmodified production output.
 * @example
 * const bytes = await exportShadow(page,'hwpx');
 */
async function exportShadow(
  page: Page,
  format: "hwp" | "hwpx" | "html",
): Promise<Buffer> {
  /** The download observer is installed before the real export action. */
  const pending = page.waitForEvent("download");
  await page.locator("#export-menu-toggle").click();
  await page.locator(`[data-export="${format}"]`).click();
  /** Exported files retain their actual native codec or standalone HTML encoding. */
  const download = await pending;
  return readFile((await download.path())!);
}

/**
 * Verify shadow preview, invalid drafts, cancellation, actual native output and undo.
 *
 * Signed direction and explicit zero stay independent of color and foreground.
 * The shared HTML drawing must retain native metadata for a real file reimport.
 * @async
 * @param {{page:Page}} context - Owned renderer bindings.
 * @returns {Promise<void>} Resolves after actual editing, output and reimport checks.
 * @throws {Error} If local drafts leak or a native writer loses source fields.
 * @example
 * // A continuous leftward shadow retains its explicit zero vertical percentage.
 */
async function verifyShadowEditing({ page }: { page: Page }): Promise<void> {
  await page.goto("/");
  await loadShadow(page);
  await openShadow(page);
  /** The actual visible group owns its radio choices independently of other native groups. */
  const group = page.getByRole("group", { name: "그림자", exact: true }),
    source = page.locator(".tiptap [data-forhan-shadow]");
  await expect(
    group.getByRole("radio", { name: "비연속", exact: true }),
  ).toBeChecked();
  await expect(page.locator('[name="shadow-x"]')).toHaveValue("-20");
  await expect(source).toHaveCSS(
    "text-shadow",
    "rgb(18, 52, 86) -4.26667px 6.4px 0px",
  );
  await page.locator('[name="shadow-x"]').fill("128");
  await page.locator('[data-modal-value="apply"]').click();
  await expect(page.locator(".native-dialog-character")).toBeVisible();
  await page.locator('[name="shadow-x"]').fill("-10");
  await page.locator('[name="shadow-y"]').fill("0");
  await group.getByRole("radio", { name: "연속", exact: true }).check();
  await page.getByRole("button", { name: "그림자 색", exact: true }).click();
  await page
    .locator(
      '#native-color-palette .cp-theme-base [data-color-value="#3a3c84"]',
    )
    .click();
  await expect(page.locator(".nd-character-sample")).toHaveCSS(
    "text-shadow",
    /rgb\(58, 60, 132\).*,/,
  );
  expect(
    JSON.parse((await source.getAttribute("data-forhan-shadow"))!).type,
  ).toBe("DROP");
  await page.locator('[data-modal-value="cancel"]:not(.modal-x)').click();
  await openShadow(page);
  await expect(page.locator('[name="shadow-x"]')).toHaveValue("-20");
  await page.locator('[name="shadow-x"]').fill("-10");
  await page.locator('[name="shadow-y"]').fill("0");
  await group.getByRole("radio", { name: "연속", exact: true }).check();
  await page.getByRole("button", { name: "그림자 색", exact: true }).click();
  await page
    .locator(
      '#native-color-palette .cp-theme-base [data-color-value="#3a3c84"]',
    )
    .click();
  await page.locator('[data-modal-value="apply"]').click();
  expect(
    JSON.parse((await source.getAttribute("data-forhan-shadow"))!),
  ).toEqual({ type: "CONTINUOUS", x: -10, y: 0, color: "#3a3c84" });
  await expect(source).toHaveCSS("color", "rgb(17, 34, 51)");
  for (/** Actual binary and XML files must agree with the source fields edited through the GUI. */ const format of [
    "hwp",
    "hwpx",
  ] as const) {
    /** Independent codec reads the complete actual browser download. */
    const bytes = await exportShadow(page, format),
      parsed = format === "hwp" ? readHwp(bytes) : await readHwpx(bytes);
    let found = false;
    for (/** Native underline and foreground remain independent of the shadow edit. */ const mark of parsed
      .doc.content![0].content![0].marks!) {
      if (mark.type === "textStyle") {
        expect(mark.attrs).toMatchObject({
          nativeShadowType: "CONTINUOUS",
          nativeShadowOffsetX: -10,
          nativeShadowOffsetY: 0,
          nativeShadowColor: "#3a3c84",
          color: "#112233",
        });
        found = true;
      }
      if (mark.type === "underline")
        expect(mark.attrs).toMatchObject({
          nativePosition: "TOP",
          nativePattern: 11,
          nativeColor: "#775533",
        });
    }
    expect(found).toBe(true);
  }
  /** Production standalone HTML retains both actual drawing CSS and original source preferences. */
  const html = await exportShadow(page, "html");
  expect(html.toString()).toContain("text-shadow:");
  await page.locator(".tiptap").press("ControlOrMeta+z");
  expect(
    JSON.parse((await source.getAttribute("data-forhan-shadow"))!).type,
  ).toBe("DROP");
  await page
    .locator("#file-input")
    .setInputFiles({
      name: "shadow.html",
      mimeType: "text/html",
      buffer: html,
    });
  await page.getByRole("button",{name:"저장 안 함",exact:true}).click();
  await expect(source).toHaveAttribute("data-forhan-shadow",JSON.stringify({ type: "CONTINUOUS", x: -10, y: 0, color: "#3a3c84" }));
  expect(
    JSON.parse((await source.getAttribute("data-forhan-shadow"))!),
  ).toEqual({ type: "CONTINUOUS", x: -10, y: 0, color: "#3a3c84" });
}
test(
  "native shadows edit, preview, cancel, validate, export and reimport without losing independent line properties",
  verifyShadowEditing,
);

/**
 * Verify partial shadow edits preserve mixed source fields and inactive preferences.
 *
 * A color-only edit must not replace different kinds and directions. Disabling
 * the effect discards invalid disabled numeric drafts and remains one undo step.
 * @async
 * @param {{page:Page}} context - Owned renderer bindings.
 * @returns {Promise<void>} Resolves after mixed source and inactive native output agree.
 * @throws {Error} If representative fields flatten source formatting or undo splits the edit.
 * @example
 * // DROP(-20,30) and CONTINUOUS(10,-10) retain their own offsets after one shared color edit.
 */
async function verifyMixedShadow({ page }: { page: Page }): Promise<void> {
  await page.goto("/");
  await loadShadow(page, true);
  await openShadow(page);
  await page.getByRole("button", { name: "그림자 색", exact: true }).click();
  await page
    .locator(
      '#native-color-palette .cp-theme-base [data-color-value="#3a3c84"]',
    )
    .click();
  await page.locator('[data-modal-value="apply"]').click();
  /** Original source identities and offsets must survive representative controls. */
  const expected = [
    { type: "DROP", x: -20, y: 30, color: "#3a3c84" },
    { type: "CONTINUOUS", x: 10, y: -10, color: "#3a3c84" },
  ];
  for (let index = 0; index < 2; index++)
    expect(
      JSON.parse(
        (await page
          .locator(".tiptap [data-forhan-shadow]")
          .nth(index)
          .getAttribute("data-forhan-shadow"))!,
      ),
    ).toEqual(expected[index]);
  await openShadow(page);
  await page.locator('[name="shadow-x"]').fill("128");
  await page
    .getByRole("group", { name: "그림자", exact: true })
    .getByRole("radio", { name: "없음", exact: true })
    .check();
  await expect(page.locator('[name="shadow-x"]')).toBeDisabled();
  await expect(
    page.getByRole("button", { name: "그림자 색", exact: true }),
  ).toBeDisabled();
  await page.locator('[data-modal-value="apply"]').click();
  for (let index = 0; index < 2; index++)
    expect(
      JSON.parse(
        (await page
          .locator(".tiptap [data-forhan-shadow]")
          .nth(index)
          .getAttribute("data-forhan-shadow"))!,
      ),
    ).toEqual({ ...expected[index], type: "NONE" });
  for (/** Both real native encodings must retain disabled direction and color preferences. */ const format of [
    "hwp",
    "hwpx",
  ] as const) {
    /** Actual output is decoded without substituting a generated test fixture. */
    const bytes = await exportShadow(page, format),
      parsed = format === "hwp" ? readHwp(bytes) : await readHwpx(bytes);
    for (let index = 0; index < 2; index++)
      for (/** Each source text-style mark owns its original signed percentages. */ const mark of parsed
        .doc.content![0].content![index].marks!)
        if (mark.type === "textStyle")
          expect(mark.attrs).toMatchObject({
            nativeShadowType: "NONE",
            nativeShadowOffsetX: expected[index].x,
            nativeShadowOffsetY: expected[index].y,
            nativeShadowColor: "#3a3c84",
          });
  }
  await page.locator(".tiptap").press("ControlOrMeta+z");
  for (let index = 0; index < 2; index++)
    expect(
      JSON.parse(
        (await page
          .locator(".tiptap [data-forhan-shadow]")
          .nth(index)
          .getAttribute("data-forhan-shadow"))!,
      ),
    ).toEqual(expected[index]);
}
test(
  "mixed native shadow edits preserve independent directions, types and disabled preferences in both native formats",
  verifyMixedShadow,
);
